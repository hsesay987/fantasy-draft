#!/usr/bin/env node
// Copies the pure game rules (app/topicDraft + app/play/{types,judging}) into backend/src/shared so the
// server runs exactly the same engines as the browser. Run: npm run sync:shared
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "backend/src/shared");
const HEADER = "// @ts-nocheck\n// GENERATED by scripts/sync-shared.mjs from the web app — do not edit; run `npm run sync:shared`.\n";

const SKIP_DIRS = new Set(["components"]);
const SKIP_FILES = new Set(["games.ts"]);

function walk(dir, rel = "") {
  const out = [];
  for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = path.join(rel, e.name);
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) out.push(...walk(dir, r));
    } else if (/\.(ts|json)$/.test(e.name) && !/\.test\.ts$/.test(e.name) && !SKIP_FILES.has(e.name)) out.push(r);
  }
  return out;
}

/** Map of destination path (relative to backend/src/shared) -> file contents. */
export function build() {
  const files = {};
  const td = path.join(root, "app/topicDraft");
  for (const r of walk(td)) files[path.join("topicDraft", r)] = fs.readFileSync(path.join(td, r), "utf8");
  for (const f of ["types.ts", "judging.ts"]) files[path.join("play", f)] = fs.readFileSync(path.join(root, "app/play", f), "utf8");
  for (const k of Object.keys(files)) if (k.endsWith(".ts")) files[k] = HEADER + files[k];
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.rmSync(OUT, { recursive: true, force: true });
  const files = build();
  for (const [k, v] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(OUT, k)), { recursive: true });
    fs.writeFileSync(path.join(OUT, k), v);
  }
  console.log(`synced ${Object.keys(files).length} files -> backend/src/shared`);
}
